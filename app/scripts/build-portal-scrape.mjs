// Builds src/portal-scrape.js from the Chrome extension's reader (extension/portal.js), so the phone app's portal sync
// keeps exactly the same privacy allow-list. Run after changing portal.js: node scripts/build-portal-scrape.mjs
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../../extension/portal.js", import.meta.url), "utf8");
const start = src.indexOf("  const clean = "), end = src.indexOf("  // One storage entry per page");
if (start < 0 || end < 0) throw new Error("portal.js layout changed: update the markers in build-portal-scrape.mjs");
const body = src.slice(start, end).trimEnd();
writeFileSync(new URL("../src/portal-scrape.js", import.meta.url), `/* GENERATED by scripts/build-portal-scrape.mjs from extension/portal.js — do not edit by hand.
   Runs inside the EWU portal page (phone app portal sync) and returns only academic lines, as JSON. */
export const SCRAPE_JS = ${JSON.stringify(`(() => {\n${body}\n  return JSON.stringify(scrape());\n})()`)};
`);
console.log("src/portal-scrape.js written");
